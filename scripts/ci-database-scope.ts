/**
 * Passwords that must never be accepted: the historical defaults (the role name
 * itself, and the generic service-container password).
 */
export const FORBIDDEN_ROLE_PASSWORDS = new Set<string>([
  'commander',
  ...DEPLOY_GATE_ROLES,
  'password',
  'changeme',
  'postgres',
]);

/**
 * Allowed password charset. Passwords are generated by the provisioner, so a
 * strict allowlist is available — and it removes SQL-literal quoting as a risk
 * surface entirely (no quotes, no backslashes, no control characters).
 */
export const PASSWORD_CHARSET = /^[A-Za-z0-9._~!@%^*+=:-]+$/;

