/**
 * ci-database-scope.ts — admission control for scripts that MUTATE a database.
 *
 * PostgreSQL roles are cluster-level objects: creating or re-password-ing one
 * affects every database in that cluster, including production databases that
 * happen to share it. So none of the following is authorization to change them:
 *
 *   - the presence of DATABASE_URL,
 *   - CI=true,
 *   - a loopback / private-network target address,
 *   - a marker row the caller could have written itself.
 *
 * Before this module existed, `ci-restore-deploy-gate-roles.ts` reset six role
 * passwords to the role name itself with no guard beyond "DATABASE_URL is set",
 * and `test:deploy-gates` invoked it as an ordinary acceptance step.
 *
 * This module implements the admission conditions that can be evaluated from
 * inside the process:
 *
 *   1. an explicit opt-in (never inferred from any ambient signal),
 *   2. a run-scoped instance identifier minted by the provisioner,
 *   3. a run-scoped provisioner credential,
 *   4. a loopback/private target address,
 *   5. per-run role passwords supplied through the environment.
 *
 * RESIDUAL GAP (recorded, not silently assumed): this does not prove that the
 * provisioner owns the instance exclusively. Doing that requires a provisioner
 * interface that this repository does not have, so a determined caller that can
 * set all of the above environment variables can still reach the mutation path.
 * These checks remove the implicit path and the public default passwords; they
 * are not a substitute for a real provisioner-owned instance identity.
 */

/** Explicit opt-in. Absence means "no" — it is never inferred. */
export const MUTATION_OPT_IN_ENV = 'COMMANDER_CI_INSTANCE_MUTATION';

/** Run-scoped instance identifier minted by the provisioner for this run. */
export const INSTANCE_ID_ENV = 'COMMANDER_CI_INSTANCE_ID';

/** Run-scoped credential the provisioner minted for this run. */
export const PROVISION_TOKEN_ENV = 'COMMANDER_CI_PROVISION_TOKEN';

export const MIN_INSTANCE_ID_LENGTH = 8;
export const MIN_PROVISION_TOKEN_LENGTH = 16;
export const MIN_ROLE_PASSWORD_LENGTH = 16;

