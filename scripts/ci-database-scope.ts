const LOOPBACK_HOSTS = new Set(['localhost', '127.0.0.1', '::1', '[::1]']);

/** Loopback or RFC1918/ULA address. A necessary condition, never sufficient. */
export function isLoopbackOrPrivateHost(host: string): boolean {
  const normalized = host.trim().toLowerCase();
  if (!normalized) return false;
  if (LOOPBACK_HOSTS.has(normalized)) return true;
  if (/^127\./.test(normalized)) return true;
  if (/^10\./.test(normalized)) return true;
  if (/^192\.168\./.test(normalized)) return true;
  if (/^172\.(1[6-9]|2\d|3[01])\./.test(normalized)) return true;
  if (/^\[?(fc|fd)[0-9a-f]{2}:/.test(normalized)) return true;
  return false;
}

export function hostOfDsn(dsn: string): string | undefined {
  try {
    return new URL(dsn).hostname || undefined;
  } catch {
    return undefined;
  }
}

/**
 * Evaluate the admission conditions for a mutating CI step.
 * Returns the list of unmet conditions; an empty list means admitted.
 */
export function assertProvisionedCiInstance(
  env: NodeJS.ProcessEnv = process.env,
  dsn?: string,
): string[] {
  const failures: string[] = [];

  if (env[MUTATION_OPT_IN_ENV] !== 'yes') {
    failures.push(
      `CI_INSTANCE_MUTATION_NOT_AUTHORIZED: set ${MUTATION_OPT_IN_ENV}=yes for a provisioned instance`,
    );
  }

  const instanceId = env[INSTANCE_ID_ENV]?.trim() ?? '';
  if (instanceId.length < MIN_INSTANCE_ID_LENGTH) {
    failures.push(
      `CI_INSTANCE_ID_REQUIRED: ${INSTANCE_ID_ENV} must be a run-scoped provisioner identifier`,
    );
  }

  const token = env[PROVISION_TOKEN_ENV]?.trim() ?? '';
  if (token.length < MIN_PROVISION_TOKEN_LENGTH) {
    failures.push(
      `CI_PROVISION_TOKEN_REQUIRED: ${PROVISION_TOKEN_ENV} must be a run-scoped provisioner credential`,
    );
  }

  if (dsn !== undefined) {
    const host = hostOfDsn(dsn);
    if (!host || !isLoopbackOrPrivateHost(host)) {
      failures.push(
        'CI_TARGET_NOT_ISOLATED: the target host is not loopback/private; refusing to mutate it',
      );
    }
  }

  return failures;
}

/**
 * Resolve a role's run-scoped password from the environment.
 * There is no default: a missing password is a failure, and the historical
 * public defaults are explicitly rejected.
 */
export function resolveRolePassword(
  role: DeployGateRole,
  env: NodeJS.ProcessEnv = process.env,
): { password?: string; failures: string[] } {
  const envName = ROLE_PASSWORD_ENV[role];
  const value = env[envName];
  if (value === undefined || value.trim().length === 0) {
    return { failures: [`CI_ROLE_PASSWORD_REQUIRED: ${envName} is not set`] };
  }
  const password = value.trim();
  const failures: string[] = [];
  // Check the known-public defaults first: that is the more precise diagnosis,
  // and some of them (e.g. "commander_owner") are also shorter than the minimum.
  if (FORBIDDEN_ROLE_PASSWORDS.has(password.toLowerCase())) {
    failures.push(`CI_ROLE_PASSWORD_INSECURE: ${envName} is a known public default`);
  }
  if (password.length < MIN_ROLE_PASSWORD_LENGTH) {
    failures.push(
      `CI_ROLE_PASSWORD_TOO_SHORT: ${envName} must be at least ${MIN_ROLE_PASSWORD_LENGTH} characters`,
    );
  }
  if (!PASSWORD_CHARSET.test(password)) {
    failures.push(
      `CI_ROLE_PASSWORD_CHARSET_INVALID: ${envName} contains characters outside the allowed set`,
    );
  }
  if (failures.length > 0) return { failures };
  return { password, failures };
}

/**
 * Render a password as a PostgreSQL string literal.
 *
 * This is defence in depth, not the primary control: `resolveRolePassword`
 * already restricts the value to a charset that contains no quote, backslash,
 * or control character, so this function can only ever wrap an already-safe
 * value. NUL bytes are rejected outright.
 */
export function sqlLiteral(value: string): string {
  if (value.includes('\u0000')) {
    throw new Error('SQL_LITERAL_NUL_REJECTED');
  }
  if (!PASSWORD_CHARSET.test(value)) {
    throw new Error('SQL_LITERAL_CHARSET_REJECTED');
  }
  return `'${value}'`;
}

/** Fail fast with a single, stable, secret-free message. */
export function formatAdmissionFailure(failures: readonly string[]): string {
  return `CI_DATABASE_MUTATION_REFUSED:\n  - ${failures.join('\n  - ')}`;
}
